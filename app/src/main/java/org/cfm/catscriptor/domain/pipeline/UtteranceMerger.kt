package org.cfm.catscriptor.domain.pipeline

interface UtteranceMerger {
    /**
     * Назначить спикера по пересечению с КАЖДЫМ исходным словом, а не со всем сегментом ASR;
     * сохранить привязку слов и объединить соседние слова/реплики одного спикера.
     * Вернуть отсортированные реплики. Реализация явно определяет поведение при равных
     * пересечениях и при их отсутствии. Перебивания не должны приводить к незаметному
     * дублированию или потере распознанных слов.
     */
    suspend fun merge(asr: List<AsrSegment>, speakers: List<SpeakerSegment>): Transcript
}
